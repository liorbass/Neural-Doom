#!/usr/bin/env python3
"""Export weights from web/mamba_nano.onnx to emulator/mamba_nano_weights.h."""

import argparse
from pathlib import Path
import onnx
from onnx import numpy_helper
import numpy as np

ROOT = Path(__file__).resolve().parent.parent
ONNX_PATH = ROOT / "web" / "mamba_nano.onnx"
OUT_HEADER = ROOT / "emulator" / "mamba_nano_weights.h"

def format_float_array(arr: np.ndarray, name: str, indent: str = "    ") -> str:
    flat = arr.flatten().astype(np.float32)
    lines = [f"static const float {name}[{len(flat)}] = {{"]
    chunk_size = 8
    for i in range(0, len(flat), chunk_size):
        chunk = flat[i : i + chunk_size]
        items = ", ".join(f"{v:.8e}f" for v in chunk)
        lines.append(f"{indent}{items},")
    lines.append("};\n")
    return "\n".join(lines)

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--onnx", default=str(ONNX_PATH))
    ap.add_argument("--out", default=str(OUT_HEADER))
    ap.add_argument("--prefix", default="MAMBA_")
    args = ap.parse_args()
    onnx_path = Path(args.onnx)
    out_header = Path(args.out)
    P = args.prefix
    print(f"Loading ONNX model from {onnx_path}...")
    model = onnx.load(str(onnx_path))
    weights = {}
    for init in model.graph.initializer:
        weights[init.name] = numpy_helper.to_array(init)

    print(f"Loaded {len(weights)} initializers. Generating {OUT_HEADER}...")

    parts = [
        "/* Auto-generated by model/export_mamba_c.py - DO NOT EDIT MANUALLY */",
        f"#ifndef {P}NANO_WEIGHTS_H",
        f"#define {P}NANO_WEIGHTS_H",
        "",
        "#include <stdint.h>",
        "",
        "#define MAMBA_D_MODEL 64",
        "#define MAMBA_D_STATE 16",
        "#define MAMBA_DT_RANK 8",
        "#define MAMBA_NUM_LAYERS 2",
        "",
    ]

    # Projections
    parts.append("/* PC and Register Projections */")
    parts.append(format_float_array(weights["onnx::MatMul_263"], f"{P}W_PC_PROJ"))       # (32, 16)
    parts.append(format_float_array(weights["model.pc_proj.bias"], f"{P}B_PC_PROJ"))     # (16,)
    parts.append(format_float_array(weights["onnx::MatMul_264"], f"{P}W_REGS_PROJ"))     # (32, 48)
    parts.append(format_float_array(weights["model.regs_proj.bias"], f"{P}B_REGS_PROJ")) # (48,)

    # Layers
    for layer in range(2):
        parts.append(f"/* Layer {layer} Weights */")
        w_in = weights[f"onnx::MatMul_{265 if layer == 0 else 287}"]      # (64, 128)
        conv_w = weights[f"model.layers.{layer}.conv1d.weight"]            # (64, 1, 3)
        conv_b = weights[f"model.layers.{layer}.conv1d.bias"]              # (64,)
        w_xproj = weights[f"onnx::MatMul_{270 if layer == 0 else 292}"]   # (64, 40)
        w_dtproj = weights[f"onnx::MatMul_{283 if layer == 0 else 305}"]  # (8, 64)
        b_dtproj = weights[f"model.layers.{layer}.dt_proj.bias"]          # (64,)
        a_log = weights[f"model.layers.{layer}.A_log"]                     # (64, 16)
        d_param = weights[f"onnx::Mul_{285 if layer == 0 else 307}"].reshape(64) # (64,)
        w_outproj = weights[f"onnx::MatMul_{286 if layer == 0 else 308}"] # (64, 64)

        # For conv1d at t=0 with padding=2, only conv_w[:, 0, 2] is used
        conv_w_t0 = conv_w[:, 0, 2]

        parts.append(format_float_array(w_in, f"{P}L{layer}_W_IN"))
        parts.append(format_float_array(conv_w_t0, f"{P}L{layer}_CONV_W"))
        parts.append(format_float_array(conv_b, f"{P}L{layer}_CONV_B"))
        parts.append(format_float_array(w_xproj, f"{P}L{layer}_W_XPROJ"))
        parts.append(format_float_array(w_dtproj, f"{P}L{layer}_W_DTPROJ"))
        parts.append(format_float_array(b_dtproj, f"{P}L{layer}_B_DTPROJ"))
        parts.append(format_float_array(a_log, f"{P}L{layer}_A_LOG"))
        parts.append(format_float_array(d_param, f"{P}L{layer}_D"))
        parts.append(format_float_array(w_outproj, f"{P}L{layer}_W_OUTPROJ"))

    # LayerNorm & Heads
    parts.append("/* Final LayerNorm & Prediction Heads */")
    parts.append(format_float_array(weights["model.ln_f.weight"], f"{P}LN_W"))
    parts.append(format_float_array(weights["model.ln_f.bias"], f"{P}LN_B"))
    parts.append(format_float_array(weights["onnx::MatMul_309"], f"{P}W_HEAD_BRANCH"))
    parts.append(format_float_array(weights["model.head_branch.bias"], f"{P}B_HEAD_BRANCH"))
    parts.append(format_float_array(weights["onnx::MatMul_310"], f"{P}W_HEAD_PC"))
    parts.append(format_float_array(weights["model.head_pc.bias"], f"{P}B_HEAD_PC"))

    parts.append(f"#endif /* {P}NANO_WEIGHTS_H */")

    out_header.parent.mkdir(parents=True, exist_ok=True)
    out_header.write_text("\n".join(parts), encoding="utf-8")
    print(f"Successfully generated {out_header} ({out_header.stat().st_size / 1024:.1f} KB).")

if __name__ == "__main__":
    main()
